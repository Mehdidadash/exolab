-- 076_repair_design_fee_double_div.sql
-- اصلاح نرخ طراحیِ کیس‌هایی که به‌دلیل اجرای دوبارهٔ مهاجرت ۰۷۴ «دوبار تقسیم» شده‌اند.
--
-- ── ریشهٔ مشکل ──
-- مهاجرت ۰۷۴ معنای `cases.design_fee` را از «جمع کل» به «فی (نرخ هر واحد)» تغییر می‌دهد
-- با یک UPDATE تقسیمی (`design_fee / quantity`). این UPDATE idempotent نیست: اگر دو بار
-- اجرا شود نرخ دوباره تقسیم می‌شود. چون ردیف ۰۷۴ در `_migrations` نبود (نسخهٔ قدیمیِ
-- دیتابیس)، runner آن را روی داده‌ای اجرا کرد که «قبلاً به‌صورت دستی تبدیل شده بود» →
-- نرخ‌های واقعی (۱۶۰٬۰۰۰) دوباره تقسیم شدند.
--
-- موارد آسیب‌دیده (طراح ۲۶، خدمات ۱ و ۲، نرخ ۱۶۰٬۰۰۰):
--   #1303 q=3 → 106666.67  باید 160000 باشد  (جمع 480,000)
--   #1304 q=1 → 480000     باید 160000 باشد  (جمع 160,000)
--   #1368 q=12 → 160000 ✅ (مقدار واقعی 160000 بود؛ دوبار تقسیم 160000/12=13333.33
--                نشد چون فایل فقط یک‌بار روی این ردیف اجرا شد — ولی چون فایل ۰۷۴
--                به‌صورت دستی روی کل جدول اجرا شد، مقدار نهایی درست شد. اینجا فقط
--                به‌عنوان مرجع تثبیت می‌شود.)
--
-- ⚠️ این UPDATEها «فی» می‌نویسند، نه جمع. مقدارها با getApplicableDesignFee
--    (price_links/overrides/default) هم‌خوانی دارند.

-- #1303 فاطمه ضیایان — خدمت ۲، ۳ واحد، طراح ۲۶ → فی ۱۶۰٬۰۰۰ (جمع ۴۸۰٬۰۰۰)
UPDATE `cases`
SET `design_fee` = 160000, `updated_at` = NOW()
WHERE `id` = 1303 AND `quantity` = 3;

-- #1304 فاطمه ضیایان — خدمت ۱، ۱ واحد، طراح ۲۶ → فی ۱۶۰٬۰۰۰
UPDATE `cases`
SET `design_fee` = 160000, `updated_at` = NOW()
WHERE `id` = 1304 AND `quantity` = 1;

-- #1368 خانوم نصیری — خدمت ۱، ۱۲ واحد، طراح ۲۶ → فی ۱۶۰٬۰۰۰ (جمع ۱٬۹۲۰٬۰۰۰)
UPDATE `cases`
SET `design_fee` = 160000, `updated_at` = NOW()
WHERE `id` = 1368 AND `quantity` = 12;

-- #1123 (در فاکتور طراح #۲ است): این کیس should-not-change است — نرخش از فاکتور می‌آید.
-- #1298 (خدمت ۱۴): نرخ طراح ۲۶ برای خدمت ۱۴ = ۶۰٬۰۰۰ است، ولی ۱۶۰٬۰۰۰ ثبت شده؛
--   این «باگِ ثبتِ قبلی» است نه دوبار تقسیم. دست نمی‌زنیم (تصمیم کاربر لازم است).

-- نشان‌دار کردن این کیس‌ها به‌عنوان «فی» (اگر نبودند).
UPDATE `cases` SET `design_fee_is_unit` = 1 WHERE `design_fee_is_unit` = 0 AND `design_fee` > 0;
