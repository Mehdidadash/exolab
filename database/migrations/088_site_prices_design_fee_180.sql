-- «فی طراحی پیش‌فرض» خدمات هم‌گروه با روکش‌های زیرکونیا که در به‌روزرسانی آبان ۱۴۰۵ جا مانده بودند.
--   خدمت ۶  = کاستوم اباتمنت اروپایی   (۱۶۰٬۰۰۰ → ۱۸۰٬۰۰۰)
--   خدمت ۷  = روکش موقت PMMA          (۱۶۰٬۰۰۰ → ۱۸۰٬۰۰۰)
-- فقط ردیف‌هایی که هنوز ۱۶۰٬۰۰۰ هستند تغییر می‌کنند (اجرای دوباره بی‌اثر است).
-- ⚠️ این تغییر روی کیس‌های قبلی اثر ندارد؛ فقط پیش‌فرضِ ثبت کیس‌های جدید را اصلاح می‌کند.

UPDATE site_prices
SET default_design_fee = 180000
WHERE id IN (6, 7)
  AND default_design_fee = 160000;
