-- 073_connection_type.sql
-- «نوع اتصال» (retention/connection type) برای کیس‌های اباتمنت.
--
-- طبق استانداردهای پروتز ایمپلنت، دو حالتِ پایهٔ نگهداشت وجود دارد:
--   • screw-retained  (پیچ‌شونده — پیچ از داخل ترمیم به اباتمنت می‌رود)
--   • cement-retained (سیمانی‌شونده — ترمیم روی اباتمنت سیمان می‌شود)
-- و حالتِ ترکیبی/دوطرفه:
--   • screw-cemented  (هم پیچ و هم سیمان؛ ترمیمِ سیمانی روی اباتمنت که خودش پیچ می‌شود)
--
-- ⚠️ «screw-cemented» و «cement-retained» معادل‌های متفاوتی هستند و نباید جابه‌جا شوند:
--    screw-cemented = اباتمنت پیچ‌شونده + روکش سیمانی‌شونده روی آن.
--
-- این ستون فقط برای کیس‌هایی معنی دارد که خدمتشان requires_scan_body = 1 است
-- (کاستوم اباتمنت کره‌ای/اروپایی و فیکسچر ایمپلنت) — در فرم همان‌جا نمایش داده می‌شود.

ALTER TABLE `cases`
  ADD COLUMN IF NOT EXISTS `connection_type` VARCHAR(30) NULL AFTER `scan_body_type_id`;
